"""Writes src/zones.rs: where each time zone is, so Luz can tell roughly where
you are from your clock, without asking for your location or the network.

    python assets/make_zones.py

Reads, at pinned versions:
  tzdata  zone.tab   the principal city of every zone, with its coordinates
  tzdata  backward   old names that still turn up ("Asia/Calcutta")
  CLDR    windowsZones.xml   Windows zone names ("E. South America Standard
                             Time") to the zone they mean ("America/Sao_Paulo")

Standard library only. The output is committed, so building needs none of this.
"""

import pathlib
import re
import urllib.request
import xml.etree.ElementTree as ET

TZDATA = "2025b"
CLDR = "release-47"

ZONE_TAB = f"https://raw.githubusercontent.com/eggert/tz/{TZDATA}/zone.tab"
BACKWARD = f"https://raw.githubusercontent.com/eggert/tz/{TZDATA}/backward"
WINDOWS = (
    f"https://raw.githubusercontent.com/unicode-org/cldr/{CLDR}"
    "/common/supplemental/windowsZones.xml"
)

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "zones.rs"


def fetch(url: str) -> str:
    with urllib.request.urlopen(url) as r:
        return r.read().decode("utf-8")


def coord(s: str, deg_digits: int) -> float:
    """+DDMM, +DDMMSS, +DDDMM or +DDDMMSS, to decimal degrees."""
    sign = -1.0 if s[0] == "-" else 1.0
    s = s[1:]
    d, rest = int(s[:deg_digits]), s[deg_digits:]
    m = int(rest[:2])
    sec = int(rest[2:4]) if len(rest) >= 4 else 0
    return sign * (d + m / 60 + sec / 3600)


def main() -> None:
    zones: dict[str, tuple[float, float]] = {}
    for line in fetch(ZONE_TAB).splitlines():
        if not line or line.startswith("#"):
            continue
        _, iso6709, name = line.split("\t")[:3]
        lat, lon = re.match(r"([+-]\d+)([+-]\d+)", iso6709).groups()
        zones[name] = (coord(lat, 2), coord(lon, 3))

    links: dict[str, str] = {}
    for line in fetch(BACKWARD).splitlines():
        parts = line.split("#", 1)[0].split()
        if len(parts) == 3 and parts[0] == "Link":
            links[parts[2]] = parts[1]

    def resolve(name: str) -> str | None:
        for _ in range(4):
            if name in zones:
                return name
            name = links.get(name, "")
        return None

    windows: dict[str, str] = {}
    root = ET.fromstring(fetch(WINDOWS))
    for z in root.iter("mapZone"):
        if z.get("territory") == "001":
            canonical = resolve(z.get("type").split()[0])
            if canonical:
                windows[z.get("other")] = canonical

    aliases = {a: resolve(t) for a, t in links.items() if resolve(t) and a not in zones}

    def f(x: float) -> str:
        return f"{x:.2f}"

    lines = [
        "//! Where each time zone is: its principal city, from tzdata, and the zone",
        "//! each Windows time zone name stands for, from CLDR. Generated by",
        f"//! `assets/make_zones.py` (tzdata {TZDATA}, CLDR {CLDR}); do not edit.",
        "",
        "/// IANA zone, latitude, longitude.",
        "pub const ZONES: &[(&str, f32, f32)] = &[",
    ]
    lines += [f'    ("{n}", {f(la)}, {f(lo)}),' for n, (la, lo) in sorted(zones.items())]
    lines += ["];", "", "/// Old IANA name, current one.", "pub const ALIASES: &[(&str, &str)] = &["]
    lines += [f'    ("{a}", "{t}"),' for a, t in sorted(aliases.items())]
    lines += ["];", "", "/// Windows time zone key name, IANA zone.", "pub const WINDOWS: &[(&str, &str)] = &["]
    lines += [f'    ("{w}", "{t}"),' for w, t in sorted(windows.items())]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(zones)} zones, {len(aliases)} aliases, {len(windows)} Windows names")


if __name__ == "__main__":
    main()
